/// Writes the launcher icon resources from the Dart art in
/// lib/icons/drift_icons.dart. A tool, not a check: run it only through
/// D:\tmp\drift_generate.bat, then review the PNGs before committing.
@Tags(['generate'])
library;

import 'dart:io';
import 'dart:typed_data';
import 'dart:ui' as ui;

import 'package:drift_time/icons/drift_icons.dart';
import 'package:flutter/rendering.dart';
import 'package:flutter_test/flutter_test.dart';

/// Relative to the project root, which is the test working directory.
const _res = 'android/app/src/main/res';

/// The adaptive-icon foreground is 108 dp at 4x. Its visible 72 dp is
/// 288 px, and the 96-unit art box fills 0.72 of that: 207.36 px, which is
/// 0.48 of the full 432 px canvas.
const _fgSize = 432;
const _fgArtScale = 0.72 * 288 / _fgSize;

/// Legacy launcher sizes for 48 dp, per density bucket.
const _legacy = {
  'mdpi': 48,
  'hdpi': 72,
  'xhdpi': 96,
  'xxhdpi': 144,
  'xxxhdpi': 192,
};

/// `meltingClock` becomes `melting_clock`.
String _snake(DriftIcon icon) => icon.name.replaceAllMapped(
  RegExp('[A-Z]'),
  (m) => '_${m[0]!.toLowerCase()}',
);

String _hex(Color c) =>
    '#${(c.toARGB32() & 0xFFFFFF).toRadixString(16).padLeft(6, '0').toUpperCase()}';

Future<Uint8List> _png(int px, CustomPainter painter) async {
  final recorder = ui.PictureRecorder();
  painter.paint(ui.Canvas(recorder), Size(px.toDouble(), px.toDouble()));
  final picture = recorder.endRecording();
  final image = await picture.toImage(px, px);
  final bytes = await image.toByteData(format: ui.ImageByteFormat.png);
  image.dispose();
  picture.dispose();
  return bytes!.buffer.asUint8List();
}

void _write(String path, Object content) {
  final file = File('$_res/$path');
  file.parent.createSync(recursive: true);
  if (content is Uint8List) {
    file.writeAsBytesSync(content);
  } else {
    file.writeAsStringSync(content as String);
  }
}

String _adaptive(String snake) =>
    '''
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by test/tool/generate_icons_test.dart. Do not edit. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_${snake}_bg" />
    <foreground android:drawable="@drawable/ic_${snake}_fg" />
</adaptive-icon>
''';

void main() {
  testWidgets('generate launcher icon resources', (tester) async {
    await tester.runAsync(() async {
      final colors = StringBuffer()
        ..writeln('<?xml version="1.0" encoding="utf-8"?>')
        ..writeln(
          '<!-- Generated by test/tool/generate_icons_test.dart. '
          'Do not edit. -->',
        )
        ..writeln('<resources>');

      for (final icon in DriftIcon.values) {
        final snake = _snake(icon);
        colors.writeln(
          '    <color name="ic_${snake}_bg">${_hex(icon.background)}</color>',
        );

        _write(
          'drawable-nodpi/ic_${snake}_fg.png',
          await _png(_fgSize, DriftIconPainter(icon, artScale: _fgArtScale)),
        );
        _write('mipmap-anydpi-v26/ic_launcher_$snake.xml', _adaptive(snake));

        for (final MapEntry(key: bucket, value: px) in _legacy.entries) {
          final png = await _png(px, DriftIconTilePainter(icon));
          _write('mipmap-$bucket/ic_launcher_$snake.png', png);
          // The app's own icon matches the default alias.
          if (icon == DriftIcon.meltingClock) {
            _write('mipmap-$bucket/ic_launcher.png', png);
          }
        }
      }

      colors.writeln('</resources>');
      _write('values/ic_launcher_colors.xml', colors.toString());
      _write(
        'mipmap-anydpi-v26/ic_launcher.xml',
        _adaptive(_snake(DriftIcon.meltingClock)),
      );
    });

    for (final icon in DriftIcon.values) {
      final snake = _snake(icon);
      expect(File('$_res/drawable-nodpi/ic_${snake}_fg.png').existsSync(), isTrue);
      expect(
        File('$_res/mipmap-xxxhdpi/ic_launcher_$snake.png').existsSync(),
        isTrue,
      );
    }
  });
}
